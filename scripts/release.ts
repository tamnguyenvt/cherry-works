/**
 * Releases one version of `cherry-works` to npm: cw and the library a tool
 * imports, in one package (FR-134 – FR-137, plan §18.4, SDK-FR-015,
 * SDK-FR-016). Everything that can fail runs before anything reaches the
 * registry or the remote. Once a push is attempted, keep the release commit
 * and tag so the local history cannot diverge from a partially updated
 * remote. A publish that fails says nothing was published (SDK-FR-019).
 *
 *   pnpm release <version>            check, then commit, tag, push and publish
 *   pnpm release <version> --dry-run  check only; package.json, README.md and
 *                                     the contract are put back
 */
import { spawnSync } from "node:child_process";
import { lstat, mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import ts from "typescript";
import { CONTRACT_FOLDER, readContractFolder, splitContract, writeContractFolder } from "./bundle-contract.js";

const ROOT = join(import.meta.dirname, "..");
const PACKAGE_JSON = join(ROOT, "package.json");
const README_MD = join(ROOT, "README.md");
const CHANGELOG_MD = join(ROOT, "CHANGELOG.md");
/** The declarations of the library the build leaves, what a tool imports. */
const LIBRARY_D_TS = join(ROOT, "dist/index.d.ts");
/** The first line of each file of the contract a release records, the
 *  contract of the last release: one folder, a file per module of the engine,
 *  none where the library was never released (SDK-FR-015). */
const contractHeaderOf = (contractFileName: string): string =>
  `// Generated by "pnpm release" from the library it published. Do not edit: it is the contract of the last release, ${contractFileName === "index.d.ts" ? "its entry: what it imports, its own declarations, and every name it exports" : `the declarations of its ${contractFileName.replace(/\.d\.ts$/, "")} module`}.`;
const RELEASE_BRANCH = "develop";
/** What installing cw may add to a machine (SC-029). */
const INSTALLED_SIZE_LIMIT = 20 * 1024 * 1024;

/** A check the release did not pass: said to the maintainer, and nothing is
 *  left changed behind it. */
class ReleaseError extends Error {}

/** A release that failed once publication began: the remote holds the
 *  release, npm does not (SDK-FR-016, SDK-FR-019). */
class PublicationError extends ReleaseError {}

/** The library's contract as a declarations file states it: each top-level
 *  declaration by its name, and each name the file exports, as its TypeScript
 *  tokens, so comments and layout are no change to it (SDK-FR-015). */
function declarationByNameOf(declarationsText: string): Map<string, string> {
  const declarationByName = new Map<string, string>();
  const sourceFile = ts.createSourceFile("index.d.ts", declarationsText, ts.ScriptTarget.Latest, false);
  const scanner = ts.createScanner(ts.ScriptTarget.Latest, true, ts.LanguageVariant.Standard);
  for (const statement of sourceFile.statements) {
    // What an import brings in shows in the declarations that use it.
    if (ts.isImportDeclaration(statement)) continue;
    const statementStart = statement.getStart(sourceFile);
    // Each token of the statement, a template literal type scanned again
    // after each substitution.
    const tokenTexts: string[] = [];
    const isTemplateBraces: boolean[] = [];
    scanner.setText(declarationsText, statementStart, statement.end - statementStart);
    for (let tokenKind = scanner.scan(); tokenKind !== ts.SyntaxKind.EndOfFileToken; tokenKind = scanner.scan()) {
      if (tokenKind === ts.SyntaxKind.OpenBraceToken || tokenKind === ts.SyntaxKind.TemplateHead)
        isTemplateBraces.push(tokenKind === ts.SyntaxKind.TemplateHead);
      else if (
        tokenKind === ts.SyntaxKind.CloseBraceToken &&
        isTemplateBraces.pop() === true &&
        scanner.reScanTemplateToken(false) === ts.SyntaxKind.TemplateMiddle
      )
        isTemplateBraces.push(true);
      tokenTexts.push(scanner.getTokenText());
    }
    const normalizedText = tokenTexts.join(" ");
    const exportListMatch = /^export \{(.*)\}(?: ;)?$/.exec(normalizedText);
    if (exportListMatch !== null) {
      for (const exportListEntry of exportListMatch[1]!.split(",")) {
        const exportText = exportListEntry.trim();
        if (exportText !== "") declarationByName.set(`export ${exportText}`, exportText);
      }
      continue;
    }
    const declarationName =
      /^(?:export )?(?:declare )?(?:abstract )?(?:class|interface|type|const enum|const|let|var|function|namespace|enum) ([\w$]+)/.exec(
        normalizedText,
      )?.[1];
    if (declarationName === undefined) {
      throw new ReleaseError(
        `the library's declarations hold a statement the contract cannot name: ${declarationsText.slice(statementStart, statement.end).replace(/\s+/g, " ")}`,
      );
    }
    const sameNameText = declarationByName.get(declarationName);
    declarationByName.set(
      declarationName,
      sameNameText === undefined ? normalizedText : `${sameNameText} ${normalizedText}`,
    );
  }
  return declarationByName;
}

const releaseArguments = process.argv.slice(2);
const version = releaseArguments.find((argument) => !argument.startsWith("--"));
const isDryRun = releaseArguments.includes("--dry-run");
const rootSpawnOptions = { cwd: ROOT, encoding: "utf8" } as const;

try {
  const packageJsonText = await readFile(PACKAGE_JSON, "utf8");
  const { name: packageName, version: currentVersion } = JSON.parse(packageJsonText) as {
    name: string;
    version: string;
  };

  // Refusals that change nothing (FR-134).
  if (version === undefined || !/^\d+\.\d+\.\d+$/.test(version)) {
    throw new ReleaseError(`"${version ?? ""}" is not a version of the form MAJOR.MINOR.PATCH, such as 0.1.0.`);
  }
  const [nextParts, currentParts] = [version, currentVersion].map((text) => text.split(".").map(Number)) as [
    number[],
    number[],
  ];
  const firstDifferenceIndex = nextParts.findIndex((nextPart, partIndex) => nextPart !== currentParts[partIndex]);
  if (firstDifferenceIndex === -1 || nextParts[firstDifferenceIndex]! < currentParts[firstDifferenceIndex]!) {
    throw new ReleaseError(`${version} is not above ${currentVersion}, the version package.json holds.`);
  }
  if (currentParts[0] === 0 && version !== "1.0.0")
    throw new ReleaseError(
      `${version} is not 1.0.0, the first version ${packageName} is released at under its contract.`,
    );

  const readmeText = await readFile(README_MD, "utf8");
  const currentVersionLines = readmeText.match(/^Current version: \*\*\d+\.\d+\.\d+\*\*$/gm) ?? [];
  if (currentVersionLines.length !== 1 || currentVersionLines[0] !== `Current version: **${currentVersion}**`) {
    throw new ReleaseError(
      `README.md must hold exactly one "Current version: **${currentVersion}**" line matching package.json.`,
    );
  }

  // Signed in to the registry, as an account that may publish this package:
  // without it, npm publish answers a misleading E404 only after the release
  // commit and tag are made. At a terminal, the maintainer is signed in here.
  let npmAccountName = spawnSync("npm", ["whoami"], rootSpawnOptions).stdout.trim();
  if (npmAccountName === "" && !isDryRun && process.stdin.isTTY) {
    console.log("Not signed in to npm. Signing in now.");
    spawnSync("npm", ["login"], { cwd: ROOT, stdio: "inherit" });
    npmAccountName = spawnSync("npm", ["whoami"], rootSpawnOptions).stdout.trim();
  }
  if (npmAccountName === "")
    throw new ReleaseError('npm has no account signed in. Run "npm login", then release again.');
  const maintainersView = spawnSync("npm", ["view", packageName, "maintainers", "--json"], rootSpawnOptions);
  if (maintainersView.status === 0) {
    const maintainers = [JSON.parse(maintainersView.stdout) as string | string[]].flat();
    if (!maintainers.some((maintainer) => maintainer.split(" ")[0] === npmAccountName)) {
      throw new ReleaseError(
        `npm is signed in as ${npmAccountName}, who does not maintain ${packageName}: ${maintainers.join(", ")}. Run "npm login" as one of them.`,
      );
    }
  }
  // A package never published answers E404; a published one without this
  // version answers nothing.
  const registryView = spawnSync("npm", ["view", `${packageName}@${version}`, "version"], rootSpawnOptions);
  if (registryView.status !== 0 && !registryView.stderr.includes("E404")) {
    throw new ReleaseError(
      `the registry could not be asked whether ${packageName} ${version} is published.\n${registryView.stderr}`,
    );
  }
  if (registryView.stdout.trim() !== "") throw new ReleaseError(`${packageName} ${version} is already published.`);

  if (spawnSync("git", ["rev-parse", "--quiet", "--verify", `refs/tags/v${version}`], rootSpawnOptions).status === 0) {
    throw new ReleaseError(`the tag v${version} already exists.`);
  }

  if (spawnSync("git", ["status", "--porcelain"], rootSpawnOptions).stdout !== "") {
    throw new ReleaseError("the working tree holds uncommitted changes. Commit or stash them, then release again.");
  }
  const currentBranch = spawnSync("git", ["branch", "--show-current"], rootSpawnOptions).stdout.trim();
  if (currentBranch !== RELEASE_BRANCH)
    throw new ReleaseError(
      `releases are made from ${RELEASE_BRANCH}, and this is ${currentBranch || "a detached HEAD"}.`,
    );
  if (spawnSync("git", ["fetch", "--quiet", "origin", RELEASE_BRANCH], rootSpawnOptions).status !== 0) {
    throw new ReleaseError(`origin/${RELEASE_BRANCH} could not be fetched.`);
  }
  const [localCommitId, remoteCommitId] = ["HEAD", `origin/${RELEASE_BRANCH}`].map((refName) =>
    spawnSync("git", ["rev-parse", refName], rootSpawnOptions).stdout.trim(),
  );
  if (localCommitId !== remoteCommitId)
    throw new ReleaseError(`${RELEASE_BRANCH} is not level with origin/${RELEASE_BRANCH}. Pull or push first.`);

  const lastContractTextByFileName = await readContractFolder(ROOT);
  if (lastContractTextByFileName === undefined && currentParts[0]! > 0) {
    throw new ReleaseError(
      `${CONTRACT_FOLDER}/ is missing, yet ${currentVersion} was released. Restore it with "git checkout v${currentVersion} -- ${CONTRACT_FOLDER}/", then release again.`,
    );
  }
  const workFolder = await mkdtemp(join(tmpdir(), "cw-release-"));
  let isRecorded = false;
  try {
    // The version written, and the library built, whose contract is judged.
    await writeFile(PACKAGE_JSON, packageJsonText.replace(`"version": "${currentVersion}"`, `"version": "${version}"`));
    await writeFile(README_MD, readmeText.replace(currentVersionLines[0]!, `Current version: **${version}**`));
    if (spawnSync("pnpm", ["build"], { cwd: ROOT, stdio: "inherit" }).status !== 0)
      throw new ReleaseError(`the tests or the build of ${packageName} fail.`);

    // The library's contract against the last release's (SDK-FR-015): a
    // declaration gone or changed breaks it, since whether a tool implements a
    // type or is handed one cannot be told; a new one adds to it. Either takes
    // at least a new minor; a new major is the maintainer's to choose.
    const builtContractText = await readFile(LIBRARY_D_TS, "utf8");
    if (lastContractTextByFileName !== undefined) {
      // Every file of the folder read together, each declaration by its name
      // wherever it is laid.
      const lastDeclarationByName = new Map<string, string>();
      for (const lastContractText of lastContractTextByFileName.values())
        for (const [declarationName, declarationText] of declarationByNameOf(lastContractText))
          lastDeclarationByName.set(
            declarationName,
            lastDeclarationByName.has(declarationName)
              ? `${lastDeclarationByName.get(declarationName)} ${declarationText}`
              : declarationText,
          );
      const builtDeclarationByName = declarationByNameOf(builtContractText);
      const brokenNames = [...lastDeclarationByName]
        .filter(([declarationName, declarationText]) => builtDeclarationByName.get(declarationName) !== declarationText)
        .map(([declarationName]) => declarationName);
      const addedNames = [...builtDeclarationByName.keys()].filter(
        (declarationName) => !lastDeclarationByName.has(declarationName),
      );
      if (brokenNames.length > 0 && firstDifferenceIndex === 2) {
        const removedNames = brokenNames.filter((declarationName) => !builtDeclarationByName.has(declarationName));
        const changedNames = brokenNames.filter((declarationName) => builtDeclarationByName.has(declarationName));
        const breakingChangeTexts = [
          removedNames.length > 0 ? `removes ${removedNames.join(", ")}` : "",
          changedNames.length > 0 ? `changes ${changedNames.join(", ")}` : "",
        ].filter((breakingChangeText) => breakingChangeText !== "");
        throw new ReleaseError(
          `${version} is a patch, yet against ${currentVersion} the contract of ${packageName} ${breakingChangeTexts.join(" and ")}. Release ${currentParts[0]}.${currentParts[1]! + 1}.0.`,
        );
      }
      if (addedNames.length > 0 && firstDifferenceIndex === 2) {
        throw new ReleaseError(
          `${version} is a patch, yet the contract of ${packageName} adds ${addedNames.join(", ")}. Release ${currentParts[0]}.${currentParts[1]! + 1}.0.`,
        );
      }
      const changelogText = await readFile(CHANGELOG_MD, "utf8").catch((changelogReadError: NodeJS.ErrnoException) => {
        if (changelogReadError.code === "ENOENT") return "";
        throw changelogReadError;
      });
      const versionSectionText =
        changelogText
          .split(/^(?=## )/m)
          .find(
            (changelogSectionText) =>
              changelogSectionText.startsWith(`## ${version} `) || changelogSectionText.startsWith(`## ${version}\n`),
          ) ?? "";
      const unlistedDeclarationNames = brokenNames
        .map((declarationName) => declarationName.split(" ").at(-1)!)
        .filter(
          (declarationName) =>
            !new RegExp(`(^|[^\\w$])${declarationName.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}([^\\w$]|$)`).test(
              versionSectionText,
            ),
        );
      if (unlistedDeclarationNames.length > 0) {
        throw new ReleaseError(
          `CHANGELOG.md must name, under "## ${version}", each change that breaks the contract of ${packageName}: ${unlistedDeclarationNames.join(", ")}.`,
        );
      }
    }

    // The contract recorded anew before the suite runs, since the suite holds
    // the build to it; put back as it was unless the release is recorded.
    await writeContractFolder(
      ROOT,
      await splitContract(ROOT, builtContractText, lastContractTextByFileName ?? new Map(), contractHeaderOf),
    );
    if (spawnSync("pnpm", ["test"], { cwd: ROOT, stdio: "inherit" }).status !== 0)
      throw new ReleaseError(`the tests or the build of ${packageName} fail.`);

    // The install check (FR-135): the one tarball that will be published,
    // installed apart from this repository and used on a fresh one.
    const packResult = spawnSync("npm", ["pack", "--json", "--pack-destination", workFolder], rootSpawnOptions);
    if (packResult.status !== 0) throw new ReleaseError(`${packageName} could not be packed.\n${packResult.stderr}`);
    const tarball = join(workFolder, (JSON.parse(packResult.stdout) as { filename: string }[])[0]!.filename);

    const installFolder = join(workFolder, "install");
    const freshRepo = join(workFolder, "repo");
    await mkdir(installFolder);
    await mkdir(freshRepo);
    const installResult = spawnSync("npm", ["install", "--prefix", installFolder, tarball], rootSpawnOptions);
    if (installResult.status !== 0) throw new ReleaseError(`${packageName} does not install.\n${installResult.stderr}`);
    spawnSync("git", ["init", "--quiet"], { cwd: freshRepo });

    const installedCw = join(installFolder, "node_modules", ".bin", "cw");
    const versionRun = spawnSync(installedCw, ["--version"], { cwd: freshRepo, encoding: "utf8" });
    if (versionRun.stdout !== `${version}\n`)
      throw new ReleaseError(`the installed cw --version prints "${versionRun.stdout.trim()}", not ${version}.`);
    for (const cwArguments of [["init", "--agent", "claude"], ["build"], ["doctor"]]) {
      const cwRun = spawnSync(installedCw, cwArguments, { cwd: freshRepo, encoding: "utf8" });
      if (cwRun.status !== 0)
        throw new ReleaseError(
          `the installed "cw ${cwArguments.join(" ")}" fails on a fresh repository.\n${cwRun.stdout}${cwRun.stderr}`,
        );
    }

    const installedEntries = await readdir(installFolder, { recursive: true, withFileTypes: true });
    const installedFileSizes = await Promise.all(
      installedEntries
        .filter((installedEntry) => installedEntry.isFile())
        .map(async (installedEntry) => (await lstat(join(installedEntry.parentPath, installedEntry.name))).size),
    );
    const installedSize = installedFileSizes.reduce((total, size) => total + size, 0);
    if (installedSize >= INSTALLED_SIZE_LIMIT) {
      throw new ReleaseError(
        `${packageName}'s install adds ${(installedSize / 1024 / 1024).toFixed(1)} MB, over the ${INSTALLED_SIZE_LIMIT / 1024 / 1024} MB it may (SC-029).`,
      );
    }

    // The library, imported from that install as a tool imports it.
    const libraryVersionRun = spawnSync(
      process.execPath,
      ["--input-type=module", "--eval", `import { VERSION } from "${packageName}"; console.info(VERSION);`],
      { cwd: installFolder, encoding: "utf8" },
    );
    if (libraryVersionRun.stdout !== `${version}\n`) {
      throw new ReleaseError(
        `the installed ${packageName} library names version "${libraryVersionRun.stdout.trim()}", not ${version}.\n${libraryVersionRun.stderr}`,
      );
    }

    if (isDryRun) {
      console.info(
        `Dry run: ${version} of ${packageName} passes every check, installed at ${(installedSize / 1024 / 1024).toFixed(1)} MB. Nothing was recorded, published or pushed.`,
      );
    } else {
      // Record and push the release before publishing the checked tarball.
      // npm asks for the account's second factor at publish time.
      if (spawnSync("git", ["add", "--all", "--", CONTRACT_FOLDER], rootSpawnOptions).status !== 0)
        throw new ReleaseError(`${CONTRACT_FOLDER}/ could not be added to the release commit.`);
      if (
        spawnSync(
          "git",
          ["commit", "--quiet", "--message", `Release ${version}`, "--", "package.json", "README.md", CONTRACT_FOLDER],
          { cwd: ROOT, stdio: "inherit" },
        ).status !== 0
      ) {
        spawnSync("git", ["reset", "--quiet", "--", CONTRACT_FOLDER], rootSpawnOptions);
        throw new ReleaseError("the release commit could not be made.");
      }
      isRecorded = true;
      // With a message, so a repository that signs its tags can make this one.
      if (
        spawnSync("git", ["tag", "--annotate", "--message", `Release ${version}`, `v${version}`], {
          cwd: ROOT,
          stdio: "inherit",
        }).status !== 0
      ) {
        spawnSync("git", ["reset", "--hard", "--quiet", "HEAD~1"], rootSpawnOptions);
        isRecorded = false;
        throw new ReleaseError(`the tag v${version} could not be made. The release commit is undone.`);
      }
      // A push may update some refs before failing. Keep local history and
      // never publish after a failed push; the maintainer can reconcile refs.
      if (
        spawnSync("git", ["push", "origin", RELEASE_BRANCH, `v${version}`], { cwd: ROOT, stdio: "inherit" }).status !==
        0
      ) {
        throw new ReleaseError(
          `the push failed; ${version} was not published. The release commit and tag are kept. Check origin, then retry: git push origin ${RELEASE_BRANCH} v${version}`,
        );
      }
      if (spawnSync("npm", ["publish", tarball], { cwd: ROOT, stdio: "inherit" }).status !== 0) {
        throw new PublicationError(
          `${packageName} ${version} could not be published, so nothing was published. ${RELEASE_BRANCH} and v${version} were pushed; the release commit and tag are kept. Confirm what is on npm first with "npm view ${packageName}@${version} version". Then, to publish ${version}, from the release commit run "pnpm build", then "npm pack" and "npm publish <tarball>".`,
        );
      }
      console.info(
        `Released ${version}: pushed ${RELEASE_BRANCH} and v${version}, then published the checked ${packageName}.`,
      );
    }
  } finally {
    if (!isRecorded) {
      await writeFile(PACKAGE_JSON, packageJsonText);
      await writeFile(README_MD, readmeText);
      if (lastContractTextByFileName === undefined)
        await rm(join(ROOT, CONTRACT_FOLDER), { recursive: true, force: true });
      else await writeContractFolder(ROOT, lastContractTextByFileName);
    }
    await rm(workFolder, { recursive: true, force: true });
  }
} catch (caughtError) {
  if (!(caughtError instanceof ReleaseError)) throw caughtError;
  console.error(
    `${caughtError instanceof PublicationError ? "Release failed during publication" : "Release refused"}: ${caughtError.message}`,
  );
  process.exitCode = 1;
}
