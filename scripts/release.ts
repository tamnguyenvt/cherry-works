/**
 * Releases one version of cw and of the engine to npm, together (FR-134 –
 * FR-137, plan §18.4, SDK-FR-015, SDK-FR-016). Everything that can fail, for
 * either package, runs before anything reaches the registry or the remote.
 * Once a push is attempted, keep the release commit and tag so the local
 * history cannot diverge from a partially updated remote.
 *
 *   pnpm release <version>            check, then commit, tag, push and publish
 *   pnpm release <version> --dry-run  check only; package.json, README.md and
 *                                     the contract are put back
 */
import { spawnSync } from "node:child_process";
import { lstat, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const PACKAGE_JSON = join(ROOT, "package.json");
const README_MD = join(ROOT, "README.md");
const CHANGELOG_MD = join(ROOT, "CHANGELOG.md");
const ENGINE_PACKAGE_NAME = "@cherry-works/engine";
const ENGINE_DIST = join(ROOT, "packages/engine/dist");
/** The engine's contract as the last release published it, recorded by each
 *  release commit; none where the engine was never released (SDK-FR-015). */
const ENGINE_CONTRACT = "packages/engine/contract.d.ts";
const ENGINE_CONTRACT_D_TS = join(ROOT, ENGINE_CONTRACT);
const CONTRACT_GENERATED_LINE = '// Generated by "pnpm release" from the engine it published. Do not edit: it is the contract of the last release.\n';
const RELEASE_BRANCH = "develop";
/** What installing cw may add to a machine (SC-029). */
const INSTALLED_SIZE_LIMIT = 20 * 1024 * 1024;

/** A check the release did not pass: said to the maintainer, and nothing is
 *  left changed behind it. */
class ReleaseError extends Error {}

/** The engine's contract as a declarations file states it: each top-level
 *  declaration by its name, and each name the file exports, with comments and
 *  layout left out, so a comment reworded is no change to it. */
function declarationByNameOf(declarationsText: string): Map<string, string> {
  const declarationByName = new Map<string, string>();
  const statementTexts = declarationsText.replace(/^\s*\/\*[\s\S]*?\*\//gm, "").replace(/^\s*\/\/.*$/gm, "").split(/\n(?=[^\s})\]])/);
  for (const statementText of statementTexts) {
    const normalizedText = statementText.replace(/\s+/g, " ").trim();
    // What an import brings in shows in the declarations that use it.
    if (normalizedText === "" || normalizedText.startsWith("import ")) continue;
    const exportListMatch = /^export \{(.*)\};?$/.exec(normalizedText);
    if (exportListMatch !== null) {
      for (const exportListEntry of exportListMatch[1]!.split(",")) {
        const exportText = exportListEntry.trim();
        if (exportText !== "") declarationByName.set(`export ${exportText}`, exportText);
      }
      continue;
    }
    const declarationName = /^(?:export )?(?:declare )?(?:abstract )?(?:class|interface|type|const enum|const|let|var|function|namespace|enum) ([\w$]+)/.exec(normalizedText)?.[1];
    if (declarationName === undefined) throw new ReleaseError(`the engine's declarations hold a statement the contract cannot name: ${normalizedText}`);
    const sameNameText = declarationByName.get(declarationName);
    declarationByName.set(declarationName, sameNameText === undefined ? normalizedText : `${sameNameText} ${normalizedText}`);
  }
  return declarationByName;
}

const releaseArguments = process.argv.slice(2);
const version = releaseArguments.find((argument) => !argument.startsWith("--"));
const isDryRun = releaseArguments.includes("--dry-run");
const rootSpawnOptions = { cwd: ROOT, encoding: "utf8" } as const;

try {
  const packageJsonText = await readFile(PACKAGE_JSON, "utf8");
  const { name: packageName, version: currentVersion } = JSON.parse(packageJsonText) as { name: string; version: string };

  // Refusals that change nothing (FR-134).
  if (version === undefined || !/^\d+\.\d+\.\d+$/.test(version)) {
    throw new ReleaseError(`"${version ?? ""}" is not a version of the form MAJOR.MINOR.PATCH, such as 0.1.0.`);
  }
  const [nextParts, currentParts] = [version, currentVersion].map((text) => text.split(".").map(Number)) as [number[], number[]];
  const firstDifferenceIndex = nextParts.findIndex((part, index) => part !== currentParts[index]);
  if (firstDifferenceIndex === -1 || nextParts[firstDifferenceIndex]! < currentParts[firstDifferenceIndex]!) {
    throw new ReleaseError(`${version} is not above ${currentVersion}, the version package.json holds.`);
  }
  if (currentParts[0] === 0 && version !== "1.0.0") throw new ReleaseError(`${version} is not 1.0.0, the first version ${packageName} and ${ENGINE_PACKAGE_NAME} are released at.`);

  const readmeText = await readFile(README_MD, "utf8");
  const currentVersionLines = readmeText.match(/^Current version: \*\*\d+\.\d+\.\d+\*\*$/gm) ?? [];
  if (currentVersionLines.length !== 1 || currentVersionLines[0] !== `Current version: **${currentVersion}**`) {
    throw new ReleaseError(`README.md must hold exactly one "Current version: **${currentVersion}**" line matching package.json.`);
  }

  // Signed in to the registry, as an account that may publish this package:
  // without it, npm publish answers a misleading E404 only after the release
  // commit and tag are made. At a terminal, the maintainer is signed in here.
  let npmAccountName = spawnSync("npm", ["whoami"], rootSpawnOptions).stdout.trim();
  if (npmAccountName === "" && !isDryRun && process.stdin.isTTY) {
    console.log("Not signed in to npm. Signing in now.");
    spawnSync("npm", ["login"], { cwd: ROOT, stdio: "inherit" });
    npmAccountName = spawnSync("npm", ["whoami"], rootSpawnOptions).stdout.trim();
  }
  if (npmAccountName === "") throw new ReleaseError('npm has no account signed in. Run "npm login", then release again.');
  for (const releasedPackageName of [packageName, ENGINE_PACKAGE_NAME]) {
    const maintainersView = spawnSync("npm", ["view", releasedPackageName, "maintainers", "--json"], rootSpawnOptions);
    if (maintainersView.status === 0) {
      const maintainers = [JSON.parse(maintainersView.stdout) as string | string[]].flat();
      if (!maintainers.some((maintainer) => maintainer.split(" ")[0] === npmAccountName)) {
        throw new ReleaseError(`npm is signed in as ${npmAccountName}, who does not maintain ${releasedPackageName}: ${maintainers.join(", ")}. Run "npm login" as one of them.`);
      }
    } else if (releasedPackageName.startsWith("@")) {
      // A scoped package never published goes out under its scope's rights:
      // an account outside the scope would publish cw, then fail on this one.
      const scopeName = releasedPackageName.slice(1, releasedPackageName.indexOf("/"));
      if (npmAccountName !== scopeName) {
        const scopeMembersView = spawnSync("npm", ["org", "ls", scopeName, "--json"], rootSpawnOptions);
        if (scopeMembersView.status !== 0) throw new ReleaseError(`the registry could not be asked who may publish under @${scopeName}.\n${scopeMembersView.stderr}`);
        const roleByMember = JSON.parse(scopeMembersView.stdout) as Record<string, string>;
        if (!(npmAccountName in roleByMember)) {
          throw new ReleaseError(`npm is signed in as ${npmAccountName}, who may not publish under @${scopeName}, so ${releasedPackageName} could not be published. Run "npm login" as a member of the ${scopeName} organization.`);
        }
      }
    }

    // A package never published answers E404; a published one without this
    // version answers nothing.
    const registryView = spawnSync("npm", ["view", `${releasedPackageName}@${version}`, "version"], rootSpawnOptions);
    if (registryView.status !== 0 && !registryView.stderr.includes("E404")) {
      throw new ReleaseError(`the registry could not be asked whether ${releasedPackageName} ${version} is published.\n${registryView.stderr}`);
    }
    if (registryView.stdout.trim() !== "") throw new ReleaseError(`${releasedPackageName} ${version} is already published.`);
  }
  if (spawnSync("git", ["rev-parse", "--quiet", "--verify", `refs/tags/v${version}`], rootSpawnOptions).status === 0) {
    throw new ReleaseError(`the tag v${version} already exists.`);
  }

  if (spawnSync("git", ["status", "--porcelain"], rootSpawnOptions).stdout !== "") {
    throw new ReleaseError('the working tree holds uncommitted changes. Commit or stash them, then release again.');
  }
  const currentBranch = spawnSync("git", ["branch", "--show-current"], rootSpawnOptions).stdout.trim();
  if (currentBranch !== RELEASE_BRANCH) throw new ReleaseError(`releases are made from ${RELEASE_BRANCH}, and this is ${currentBranch || "a detached HEAD"}.`);
  if (spawnSync("git", ["fetch", "--quiet", "origin", RELEASE_BRANCH], rootSpawnOptions).status !== 0) {
    throw new ReleaseError(`origin/${RELEASE_BRANCH} could not be fetched.`);
  }
  const [localCommitId, remoteCommitId] = ["HEAD", `origin/${RELEASE_BRANCH}`].map((refName) => spawnSync("git", ["rev-parse", refName], rootSpawnOptions).stdout.trim());
  if (localCommitId !== remoteCommitId) throw new ReleaseError(`${RELEASE_BRANCH} is not level with origin/${RELEASE_BRANCH}. Pull or push first.`);

  const lastContractText = await readFile(ENGINE_CONTRACT_D_TS, "utf8").catch((contractReadError: NodeJS.ErrnoException) => {
    if (contractReadError.code === "ENOENT") return undefined;
    throw contractReadError;
  });
  if (lastContractText === undefined && currentParts[0]! > 0) {
    throw new ReleaseError(`${ENGINE_CONTRACT} is missing, yet ${currentVersion} was released. Restore it with "git show v${currentVersion}:${ENGINE_CONTRACT}", then release again.`);
  }
  const workFolder = await mkdtemp(join(tmpdir(), "cw-release-"));
  let isRecorded = false;
  try {
    // The version written, and the suite run, which builds.
    await writeFile(PACKAGE_JSON, packageJsonText.replace(`"version": "${currentVersion}"`, `"version": "${version}"`));
    await writeFile(README_MD, readmeText.replace(currentVersionLines[0]!, `Current version: **${version}**`));
    if (spawnSync("pnpm", ["test"], { cwd: ROOT, stdio: "inherit" }).status !== 0) throw new ReleaseError(`the tests or the build of ${packageName} and ${ENGINE_PACKAGE_NAME} fail.`);

    // The engine's contract against the last release's (SDK-FR-015): a
    // declaration gone or changed breaks it, since whether a tool implements a
    // type or is handed one cannot be told; a new one adds to it.
    const builtContractText = await readFile(join(ENGINE_DIST, "index.d.ts"), "utf8");
    if (lastContractText !== undefined) {
      const lastDeclarationByName = declarationByNameOf(lastContractText);
      const builtDeclarationByName = declarationByNameOf(builtContractText);
      const brokenNames = [...lastDeclarationByName].filter(([declarationName, declarationText]) => builtDeclarationByName.get(declarationName) !== declarationText).map(([declarationName]) => declarationName);
      const addedNames = [...builtDeclarationByName.keys()].filter((declarationName) => !lastDeclarationByName.has(declarationName));
      if (brokenNames.length > 0 && firstDifferenceIndex > 0) {
        throw new ReleaseError(`${version} is not a new major, yet the engine's contract changes against ${currentVersion}: ${brokenNames.join(", ")}. Release ${currentParts[0]! + 1}.0.0.`);
      }
      if (addedNames.length > 0 && firstDifferenceIndex === 2) {
        throw new ReleaseError(`${version} is a patch, yet the engine's contract adds ${addedNames.join(", ")}. Release ${currentParts[0]}.${currentParts[1]! + 1}.0.`);
      }
      const changelogText = await readFile(CHANGELOG_MD, "utf8").catch((changelogReadError: NodeJS.ErrnoException) => {
        if (changelogReadError.code === "ENOENT") return "";
        throw changelogReadError;
      });
      const versionSectionText = changelogText.split(/^(?=## )/m).find((changelogSectionText) => changelogSectionText.startsWith(`## ${version} `) || changelogSectionText.startsWith(`## ${version}\n`)) ?? "";
      const unlistedDeclarationNames = brokenNames.map((declarationName) => declarationName.split(" ").at(-1)!).filter((declarationName) => !new RegExp(`(^|[^\\w$])${declarationName.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}([^\\w$]|$)`).test(versionSectionText));
      if (unlistedDeclarationNames.length > 0) {
        throw new ReleaseError(`CHANGELOG.md must name, under "## ${version}", each change that breaks the engine's contract: ${unlistedDeclarationNames.join(", ")}.`);
      }
    }

    // The install check (FR-135): the one tarball that will be published,
    // installed apart from this repository and used on a fresh one.
    const packResult = spawnSync("npm", ["pack", "--json", "--pack-destination", workFolder], rootSpawnOptions);
    if (packResult.status !== 0) throw new ReleaseError(`${packageName} could not be packed.\n${packResult.stderr}`);
    const tarball = join(workFolder, (JSON.parse(packResult.stdout) as { filename: string }[])[0]!.filename);

    const installFolder = join(workFolder, "install");
    const freshRepo = join(workFolder, "repo");
    await mkdir(installFolder);
    await mkdir(freshRepo);
    const installResult = spawnSync("npm", ["install", "--prefix", installFolder, tarball], rootSpawnOptions);
    if (installResult.status !== 0) throw new ReleaseError(`${packageName} does not install.\n${installResult.stderr}`);
    spawnSync("git", ["init", "--quiet"], { cwd: freshRepo });

    const installedCw = join(installFolder, "node_modules", ".bin", "cw");
    const versionRun = spawnSync(installedCw, ["--version"], { cwd: freshRepo, encoding: "utf8" });
    if (versionRun.stdout !== `${version}\n`) throw new ReleaseError(`the installed cw --version prints "${versionRun.stdout.trim()}", not ${version}.`);
    for (const cwArguments of [["init", "--agent", "claude"], ["build"], ["doctor"]]) {
      const cwRun = spawnSync(installedCw, cwArguments, { cwd: freshRepo, encoding: "utf8" });
      if (cwRun.status !== 0) throw new ReleaseError(`the installed "cw ${cwArguments.join(" ")}" fails on a fresh repository.\n${cwRun.stdout}${cwRun.stderr}`);
    }

    const installedEntries = await readdir(installFolder, { recursive: true, withFileTypes: true });
    const installedFileSizes = await Promise.all(
      installedEntries.filter((entry) => entry.isFile()).map(async (entry) => (await lstat(join(entry.parentPath, entry.name))).size),
    );
    const installedSize = installedFileSizes.reduce((total, size) => total + size, 0);
    if (installedSize >= INSTALLED_SIZE_LIMIT) {
      throw new ReleaseError(`${packageName}'s install adds ${(installedSize / 1024 / 1024).toFixed(1)} MB, over the ${INSTALLED_SIZE_LIMIT / 1024 / 1024} MB it may (SC-029).`);
    }

    // The engine's install check: its one tarball, installed apart and imported.
    const enginePackResult = spawnSync("npm", ["pack", "--json", "--pack-destination", workFolder], { cwd: ENGINE_DIST, encoding: "utf8" });
    if (enginePackResult.status !== 0) throw new ReleaseError(`${ENGINE_PACKAGE_NAME} could not be packed.\n${enginePackResult.stderr}`);
    const engineTarball = join(workFolder, (JSON.parse(enginePackResult.stdout) as { filename: string }[])[0]!.filename);
    const engineInstallFolder = join(workFolder, "engine-install");
    await mkdir(engineInstallFolder);
    const engineInstallResult = spawnSync("npm", ["install", "--prefix", engineInstallFolder, engineTarball], rootSpawnOptions);
    if (engineInstallResult.status !== 0) throw new ReleaseError(`${ENGINE_PACKAGE_NAME} does not install.\n${engineInstallResult.stderr}`);
    const engineVersionRun = spawnSync(process.execPath, ["--input-type=module", "--eval", `import { VERSION } from "${ENGINE_PACKAGE_NAME}"; console.info(VERSION);`], { cwd: engineInstallFolder, encoding: "utf8" });
    if (engineVersionRun.stdout !== `${version}\n`) {
      throw new ReleaseError(`the installed ${ENGINE_PACKAGE_NAME} names version "${engineVersionRun.stdout.trim()}", not ${version}.\n${engineVersionRun.stderr}`);
    }

    if (isDryRun) {
      console.info(`Dry run: ${version} of ${packageName} and ${ENGINE_PACKAGE_NAME} passes every check, ${packageName} installed at ${(installedSize / 1024 / 1024).toFixed(1)} MB. Nothing was recorded, published or pushed.`);
    } else {
      // Record and push the release before publishing the checked tarball.
      // npm asks for the account's second factor at publish time.
      await writeFile(ENGINE_CONTRACT_D_TS, CONTRACT_GENERATED_LINE + builtContractText);
      if (spawnSync("git", ["add", "--", ENGINE_CONTRACT], rootSpawnOptions).status !== 0) throw new ReleaseError(`${ENGINE_CONTRACT} could not be added to the release commit.`);
      if (spawnSync("git", ["commit", "--quiet", "--message", `Release ${version}`, "--", "package.json", "README.md", ENGINE_CONTRACT], { cwd: ROOT, stdio: "inherit" }).status !== 0) {
        spawnSync("git", ["reset", "--quiet", "--", ENGINE_CONTRACT], rootSpawnOptions);
        throw new ReleaseError("the release commit could not be made.");
      }
      isRecorded = true;
      // With a message, so a repository that signs its tags can make this one.
      if (spawnSync("git", ["tag", "--annotate", "--message", `Release ${version}`, `v${version}`], { cwd: ROOT, stdio: "inherit" }).status !== 0) {
        spawnSync("git", ["reset", "--hard", "--quiet", "HEAD~1"], rootSpawnOptions);
        isRecorded = false;
        throw new ReleaseError(`the tag v${version} could not be made. The release commit is undone.`);
      }
      // A push may update some refs before failing. Keep local history and
      // never publish after a failed push; the maintainer can reconcile refs.
      if (spawnSync("git", ["push", "origin", RELEASE_BRANCH, `v${version}`], { cwd: ROOT, stdio: "inherit" }).status !== 0) {
        throw new ReleaseError(`the push failed; ${version} was not published. The release commit and tag are kept. Check origin, then retry: git push origin ${RELEASE_BRANCH} v${version}`);
      }
      if (spawnSync("npm", ["publish", tarball], { cwd: ROOT, stdio: "inherit" }).status !== 0) {
        throw new ReleaseError(`npm publish failed after ${RELEASE_BRANCH} and v${version} were pushed; neither package was published. The release commit and tag are kept. From that release commit, run "npm pack", then "npm publish <tarball>", then "pnpm build", "npm pack ./packages/engine/dist" and "npm publish <engine tarball> --access public" to retry.`);
      }
      if (spawnSync("npm", ["publish", engineTarball, "--access", "public"], { cwd: ROOT, stdio: "inherit" }).status !== 0) {
        throw new ReleaseError(`${packageName} ${version} was published, but ${ENGINE_PACKAGE_NAME} was not. From the release commit, run "pnpm build", then "npm pack ./packages/engine/dist", then "npm publish <tarball> --access public" to retry.`);
      }
      console.info(`Released ${version}: pushed ${RELEASE_BRANCH} and v${version}, then published the checked ${packageName} and ${ENGINE_PACKAGE_NAME}.`);
    }
  } finally {
    if (!isRecorded) {
      await writeFile(PACKAGE_JSON, packageJsonText);
      await writeFile(README_MD, readmeText);
      if (lastContractText === undefined) await rm(ENGINE_CONTRACT_D_TS, { force: true });
      else await writeFile(ENGINE_CONTRACT_D_TS, lastContractText);
    }
    await rm(workFolder, { recursive: true, force: true });
  }
} catch (raised) {
  if (!(raised instanceof ReleaseError)) throw raised;
  console.error(`Release refused: ${raised.message}`);
  process.exitCode = 1;
}
