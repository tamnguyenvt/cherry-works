    assert.match(releaseRun.stderr, /Confirm what is on npm first with "npm view cherry-works@1\.1\.0 version" and "npm view @cherry-works\/engine@1\.1\.0 version"\. Then, to publish @cherry-works\/engine at 1\.1\.0, from the release commit run "pnpm build", then "npm pack \.\/packages\/engine\/dist", then "npm publish <tarball> --access public"\./);
    assert.doesNotMatch(releaseRun.stderr, /Release refused|rolled back/);
    const publishCommands = (await releaseCommandsIn(fixtureFolder)).filter(([commandName, action]) => commandName === "npm" && action === "publish");
