import { test } from "node:test";
import assert from "node:assert/strict";
import { access, readFile } from "node:fs/promises";
import { join } from "node:path";
import { inARelease } from "./a-release.js";

const LAST_CONTRACT = `import { z } from 'zod';

/** Reads the files of a repository. */
interface ForReadingFiles {
    readIfThere(file: URL): Promise<string | undefined>;
    listFiles(folder: URL): Promise<readonly URL[]>;
}
declare const VERSION: string;

export { type ForReadingFiles, VERSION };
`;
const NARROWED_CONTRACT = LAST_CONTRACT.replace("    listFiles(folder: URL): Promise<readonly URL[]>;\n", "");
const CHANGED_CONTRACT = LAST_CONTRACT.replace("Promise<string | undefined>", "Promise<string>");
const UNEXPORTED_CONTRACT = LAST_CONTRACT.replace("type ForReadingFiles, ", "");
const WIDENED_CONTRACT = LAST_CONTRACT
  .replace("declare const VERSION", "interface ForTellingTime {\n    now(): Date;\n}\ndeclare const VERSION")
  .replace("VERSION };", "type ForTellingTime, VERSION };");
const IMPORT_GROWN_CONTRACT = WIDENED_CONTRACT.replace("import { z } from 'zod';", "import { z, ZodError } from 'zod';");
const REWORDED_CONTRACT = LAST_CONTRACT.replace("/** Reads the files of a repository. */", "/**\n * Reads every file a repository holds.\n */");
const GLOB_CONTRACT = LAST_CONTRACT.replace("declare const VERSION", 'type CharterGlob = "**/*.md" | "docs*/";\ndeclare const VERSION').replace("VERSION };", "type CharterGlob, VERSION };");
const OPTIONAL_MEMBER_CONTRACT = LAST_CONTRACT.replace("    listFiles(folder: URL): Promise<readonly URL[]>;\n", "    listFiles(folder: URL): Promise<readonly URL[]>;\n    isWritable?(file: URL): Promise<boolean>;\n");
const RELAID_CONTRACT = LAST_CONTRACT
  .replace("readIfThere(file: URL)", "readIfThere(file:URL)")
  .replace("Promise<readonly URL[]>;", "Promise<readonly URL[]>; /** Every file under it. */")
  .replace("declare const VERSION: string;", "/** The engine's version. */ declare const VERSION: string; // As published.")
  .replace("interface ForReadingFiles {", "  interface ForReadingFiles {");
const GENERATED_LINE = '// Generated by "pnpm release" from the engine it published. Do not edit: it is the contract of the last release.\n';

async function releaseCommandsIn(fixtureFolder: string): Promise<string[][]> {
  return (await readFile(join(fixtureFolder, "release-commands.jsonl"), "utf8")).trim().split("\n").map((commandLine) => JSON.parse(commandLine));
}

function assertNothingReleased(releaseCommands: string[][]): void {
  assert.equal(releaseCommands.some(([commandName, action]) => commandName === "npm" && action === "publish"), false, "nothing may be published");
  assert.equal(releaseCommands.some(([commandName, action]) => commandName === "git" && ["commit", "tag", "push"].includes(action!)), false, "nothing may be recorded");
}

test("a release that passes publishes cw and the engine at its version, and records the engine's contract (SDK Story 4 scenario 1)", async () => {
  await inARelease({ currentVersion: "1.0.0", nextVersion: "1.1.0", releaseMode: "publish", builtContractText: LAST_CONTRACT, lastContractText: LAST_CONTRACT }, async (releaseRun, fixtureFolder) => {
    assert.equal(releaseRun.status, 0, releaseRun.stderr);
    const releaseCommands = await releaseCommandsIn(fixtureFolder);
    const pushIndex = releaseCommands.findIndex(([commandName, action]) => commandName === "git" && action === "push");
    const publishCommands = releaseCommands.filter(([commandName, action]) => commandName === "npm" && action === "publish");
    assert.deepEqual(publishCommands.map((publishCommand) => publishCommand.slice(1).map((publishArgument) => publishArgument.replace(/^.*\//, ""))), [["publish", "fixture.tgz"], ["publish", "engine.tgz", "--access", "public"]]);
    assert.ok(releaseCommands.indexOf(publishCommands[0]!) > pushIndex, "push must precede publish");
    const recordedRelease = JSON.parse(await readFile(join(fixtureFolder, "recorded-release.json"), "utf8"));
    assert.ok(recordedRelease.arguments.includes("packages/engine/contract.d.ts"));
    assert.equal(recordedRelease.contract, GENERATED_LINE + LAST_CONTRACT);
    assert.match(releaseRun.stdout, /cherry-works.*@cherry-works\/engine|@cherry-works\/engine.*cherry-works/);
  });
});

test("a first release dry run checks both packages at 1.0.0, publishes neither and writes no contract (SDK Story 4 scenario 1)", async () => {
  await inARelease({ currentVersion: "0.9.0", nextVersion: "1.0.0", releaseMode: "dry-run", builtContractText: LAST_CONTRACT }, async (releaseRun, fixtureFolder) => {
    assert.equal(releaseRun.status, 0, releaseRun.stderr);
    const releaseCommands = await releaseCommandsIn(fixtureFolder);
    assertNothingReleased(releaseCommands);
    const installedTarballs = releaseCommands.filter(([commandName, action]) => commandName === "npm" && action === "install").map((installCommand) => installCommand.at(-1)!.replace(/^.*\//, ""));
    assert.deepEqual(installedTarballs.sort(), ["engine.tgz", "fixture.tgz"]);
    await assert.rejects(access(join(fixtureFolder, "packages/engine/contract.d.ts")));
    assert.match(releaseRun.stdout, /1\.0\.0/);
    assert.match(releaseRun.stdout, /@cherry-works\/engine/);
  });
});

for (const nextVersion of ["0.9.1", "1.1.0", "2.0.0"]) {
  test(`a first release at ${nextVersion} is refused, since both packages are first released at 1.0.0`, async () => {
    await inARelease({ currentVersion: "0.9.0", nextVersion, releaseMode: "dry-run", builtContractText: LAST_CONTRACT }, async (releaseRun, fixtureFolder) => {
      assert.equal(releaseRun.status, 1);
      assert.match(releaseRun.stderr, new RegExp(`${nextVersion.replaceAll(".", "\\.")} is not 1\\.0\\.0`));
      await assert.rejects(access(join(fixtureFolder, "release-commands.jsonl")), "no command may run");
    });
  });
}

