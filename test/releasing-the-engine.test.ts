async function releaseCommandsIn(fixtureFolder: string): Promise<string[][]> {
  return (await readFile(join(fixtureFolder, "release-commands.jsonl"), "utf8"))
    .trim()
    .split("\n")
    .map((commandLine) => JSON.parse(commandLine));
}

function assertNothingReleased(releaseCommands: string[][]): void {
  assert.equal(
    releaseCommands.some(([commandName, action]) => commandName === "npm" && action === "publish"),
    false,
    "nothing may be published",
  );
  assert.equal(
    releaseCommands.some(
      ([commandName, action]) => commandName === "git" && ["commit", "tag", "push"].includes(action!),
    ),
    false,
    "nothing may be recorded",
  );
}

test("a release that passes publishes cherry-works, cw and its library, at its version, and records the library's contract (SDK Story 4 scenario 1, CORE Story 15 scenario 1)", async () => {
  await inARelease(
    {
      currentVersion: "1.0.0",
      nextVersion: "1.1.0",
      releaseMode: "publish",
      builtContractText: LAST_CONTRACT,
      lastContractText: LAST_CONTRACT,
    },
    async (releaseRun, fixtureFolder) => {
      assert.equal(releaseRun.status, 0, releaseRun.stderr);
      const releaseCommands = await releaseCommandsIn(fixtureFolder);
      const pushIndex = releaseCommands.findIndex(
        ([commandName, action]) => commandName === "git" && action === "push",
      );
      const publishCommands = releaseCommands.filter(
        ([commandName, action]) => commandName === "npm" && action === "publish",
      );
      assert.deepEqual(
        publishCommands.map((publishCommand) =>
          publishCommand.slice(1).map((publishArgument) => publishArgument.replace(/^.*\//, "")),
        ),
        [["publish", "fixture.tgz"]],
      );
      assert.ok(releaseCommands.indexOf(publishCommands[0]!) > pushIndex, "push must precede publish");
      const recordedRelease = JSON.parse(await readFile(join(fixtureFolder, "recorded-release.json"), "utf8"));
      assert.ok(recordedRelease.arguments.includes("contract"));
      assert.deepEqual(Object.keys(recordedRelease.contract), ["index.d.ts"]);
      const recordedEntryText: string = recordedRelease.contract["index.d.ts"];
      assert.match(
        recordedEntryText.split("\n")[0]!,
        /^\/\/ Generated by "pnpm release" from the library it published\. Do not edit: it is the contract of the last release, its entry/,
      );
      assert.match(recordedEntryText, /interface ForReadingFiles \{/);
      assert.match(recordedEntryText, /export \{ type ForReadingFiles, VERSION \};/);
      // At that version: the package packed, the release commit and its tag
      // all name it.
      assert.equal(JSON.parse(await readFile(join(fixtureFolder, "packed-package.json"), "utf8")).version, "1.1.0");
      assert.equal(JSON.parse(recordedRelease.packageJson).version, "1.1.0");
      assert.ok(recordedRelease.arguments.includes("package.json"));
      const tagCommand = releaseCommands.find(([commandName, action]) => commandName === "git" && action === "tag");
      assert.equal(tagCommand?.at(-1), "v1.1.0");
      assert.match(releaseRun.stdout, /published the checked cherry-works\.$/m);
    },
  );
});

