const repo = new URL("file:///repo/");
const inRepo = (path: string) => new URL(path, repo);
const primitiveText = (kind: string, id: string, headers = "") =>
  `---\nkind: ${kind}\nid: ${id}\ndescription: Instructions for ${id}.\n${headers}---\n\nFollow ${id}.\n`;

const building = (files: Readonly<Record<string, string>> = {}) => {
  const held = new InMemoryFileReaders({ [inRepo(".cw/settings.json").href]: '{"agents":["codex"]}', ...files });
  const charterRuntimeApps = buildingCharterOf(
    held,
    new InMemoryFileOutput(held),
    new InMemoryTokenCounter(),
    {},
    new InMemoryReporter(),
    {},
  );
  return { held, charterRuntimeApps };
};

test("Codex cleanup finds stamped nested AGENTS.md without a registry and preserves authored files", async () => {
  const guideFile = inRepo(".cw/charter/primitive/guide/types/index.md");
  const { held, charterRuntimeApps } = building({
    [guideFile.href]: primitiveText("guide", "types", 'globs: ["src/**"]\n'),
  });
  assert.equal((await charterRuntimeApps.buildCharter()).type, "ProjectionPlanSummary");
  const generatedText = await held.readFile(inRepo("src/AGENTS.md"));
  assert.match(generatedText, /Generated by cherry-works/);
  held.writeFile(inRepo("orphan/AGENTS.md"), generatedText);
  held.writeFile(inRepo("authored/AGENTS.md"), "Keep authored instructions.\n");
  held.writeFile(inRepo("mixed/AGENTS.md"), `Keep authored instructions.\n${generatedText}`);
  held.removeFile(guideFile);
  const preview = await charterRuntimeApps.previewCharterBuild();
  assert.equal(preview.type, "ProjectionPlanSummary");
  if (preview.type === "ProjectionPlanSummary") {
    assert.ok(preview.data.deleted.includes("src/AGENTS.md"));
    assert.ok(preview.data.deleted.includes("orphan/AGENTS.md"));
    assert.ok(!preview.data.deleted.includes("authored/AGENTS.md"));
    assert.ok(!preview.data.deleted.includes("mixed/AGENTS.md"));
  }
  assert.equal(await held.readFile(inRepo("src/AGENTS.md")), generatedText);
  assert.equal((await charterRuntimeApps.buildCharter()).type, "ProjectionPlanSummary");
  assert.equal(await held.readIfThere(inRepo("src/AGENTS.md")), undefined);
  assert.equal(await held.readIfThere(inRepo("orphan/AGENTS.md")), undefined);
  assert.equal(await held.readFile(inRepo("authored/AGENTS.md")), "Keep authored instructions.\n");
  assert.equal(await held.readFile(inRepo("mixed/AGENTS.md")), "Keep authored instructions.\n");
  assert.ok(!held.calls.includes("files under file:///repo/"));
});

