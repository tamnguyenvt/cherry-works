const repo = new URL("file:///repo/");
const inRepo = (path: string) => new URL(path, repo);
const primitiveText = (kind: string, id: string, headers = "") => `---\nkind: ${kind}\nid: ${id}\ndescription: Instructions for ${id}.\n${headers}---\n\nFollow ${id}.\n`;

const building = (files: Readonly<Record<string, string>> = {}) => {
  const held = new InMemoryFileReaders({ [inRepo(".cw/settings.json").href]: '{"agents":["codex"]}', ...files });
  const charterAuthoringApp = new CharterAuthoring(repo, held, new YamlParser(), new InMemoryFileOutput(held), new InMemoryVCS(), new InMemoryTokenCounter(), {}, undefined, undefined, undefined, new TomlParser());
  return { held, charterAuthoringApp };
};

test("Codex cleanup finds stamped nested AGENTS.md without a registry and preserves authored files", async () => {
  const guideFile = inRepo(".cw/charter/guide/types/index.md");
  const { held, charterAuthoringApp } = building({
    [guideFile.href]: primitiveText("guide", "types", 'globs: ["src/**"]\n'),
  });
  assert.equal((await charterAuthoringApp.build()).type, "PlanSummary");
  const generatedText = await held.read(inRepo("src/AGENTS.md"));
  assert.match(generatedText, /Generated by cherry-works/);
  held.write(inRepo("orphan/AGENTS.md"), generatedText);
  held.write(inRepo("authored/AGENTS.md"), "Keep authored instructions.\n");
  held.write(inRepo("mixed/AGENTS.md"), `Keep authored instructions.\n${generatedText}`);
  held.remove(guideFile);
  const preview = await charterAuthoringApp.preview();
  assert.equal(preview.type, "PlanSummary");
  if (preview.type === "PlanSummary") {
    assert.ok(preview.data.deleted.includes("src/AGENTS.md"));
    assert.ok(preview.data.deleted.includes("orphan/AGENTS.md"));
    assert.ok(!preview.data.deleted.includes("authored/AGENTS.md"));
    assert.ok(!preview.data.deleted.includes("mixed/AGENTS.md"));
  }
  assert.equal(await held.read(inRepo("src/AGENTS.md")), generatedText);
  assert.equal((await charterAuthoringApp.build()).type, "PlanSummary");
  assert.equal(await held.readIfThere(inRepo("src/AGENTS.md")), undefined);
  assert.equal(await held.readIfThere(inRepo("orphan/AGENTS.md")), undefined);
  assert.equal(await held.read(inRepo("authored/AGENTS.md")), "Keep authored instructions.\n");
  assert.equal(await held.read(inRepo("mixed/AGENTS.md")), "Keep authored instructions.\n");
  assert.ok(!held.calls.includes("files under file:///repo/"));
});

