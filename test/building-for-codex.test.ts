test("shared entries appear once in the common catalogue and provider catalogues contain only restricted entries", async () => {
  const { held, charterAuthoringApp } = building({
    [inRepo(".cw/settings.json").href]: '{"agents":["claude","codex"]}',
    [inRepo(".cw/out/catalog.json").href]: '[{"id":"obsolete"}]',
    [inRepo(".cw/charter/guide/shared/index.md").href]: primitiveText("guide", "shared"),
    [inRepo(".cw/charter/sensor/empty-list/index.md").href]: primitiveText("sensor", "empty-list", "agent-provider: []\nsignal: Stop\nrun: echo empty\n"),
    [inRepo(".cw/charter/posture/all-providers/index.md").href]: primitiveText("posture", "all-providers", 'agent-provider: [claude, codex]\nallow: ["Bash(echo:*)"]\ndeny: ["Bash(echo secret:*)"]\n'),
  });
  assert.equal((await charterAuthoringApp.build()).type, "PlanSummary");
  assert.equal(await held.readIfThere(inRepo(".cw/out/catalog.json")), undefined);
  const commonCatalogueText = await held.read(inRepo(".cw/out/catalogue.json"));
  const commonEntries = JSON.parse(commonCatalogueText) as { id: string }[];
  assert.ok(commonEntries.some((entry) => entry.id === "shared"));
  assert.ok(commonEntries.some((entry) => entry.id === "empty-list"));
  assert.ok(commonEntries.some((entry) => entry.id === "all-providers"));
  assert.ok(!commonEntries.some((entry) => entry.id === "cw-session-tokens-counter-on-stop"));
  assert.doesNotMatch(commonCatalogueText, /agent-provider/);
  for (const agent of ["claude", "codex"]) {
    const catalogueText = await held.read(inRepo(`.cw/out/catalogue.${agent}.json`));
    const catalogueEntries = JSON.parse(catalogueText) as { id: string }[];
    assert.ok(!catalogueEntries.some((entry) => commonEntries.some((commonEntry) => commonEntry.id === entry.id)));
    assert.equal(catalogueEntries.some((entry) => entry.id === "cw-session-tokens-counter-on-stop"), agent === "claude");
    assert.doesNotMatch(catalogueText, /agent-provider/);
  }
  held.write(inRepo(".cw/settings.json"), '{"agents":["codex"]}');
  assert.equal((await charterAuthoringApp.build()).type, "PlanSummary");
  assert.equal(await held.readIfThere(inRepo(".cw/out/catalogue.claude.json")), undefined);
  assert.ok(await held.readIfThere(inRepo(".cw/out/catalogue.codex.json")));
  assert.equal(await held.read(inRepo(".cw/out/catalogue.json")), commonCatalogueText);
});
