test("embedded guides include mixins, keep links rooted correctly and count their body once", async () => {
  const guideFile = inRepo(".cw/charter/guide/team/general/index.md");
  const { held, charterAuthoringApp } = building({
    [guideFile.href]: primitiveText("guide", "team/general", "globs: []\nmixins: [opening]\n") + '\nRead [[reference]] and [asset](./notes.md). Keep `./notes.md` literal.\n',
    [inRepo(".cw/charter/guide/team/general/notes.md").href]: "Guide asset.",
    [inRepo(".cw/charter/mixin/opening/index.md").href]: primitiveText("mixin", "opening"),
    [inRepo(".cw/charter/corpus/reference/index.md").href]: primitiveText("corpus", "reference"),
    [inRepo(".cw/charter/guide/scoped/index.md").href]: primitiveText("guide", "scoped", 'globs: ["src/**"]\n'),
  });
  assert.equal((await charterAuthoringApp.build()).type, "PlanSummary");
  const entryText = await held.read(inRepo("AGENTS.md"));
  assert.match(entryText, /Follow opening\.[\s\S]*Follow team\/general\./);
  assert.match(entryText, /\[reference\]\(\.\/\.cw\/out\/corpus\/reference\/index.md\)/);
  assert.match(entryText, /\[asset\]\(\.\/\.cw\/out\/guide\/team\/general\/notes.md\)/);
  assert.match(entryText, /`\.\/notes.md` literal/);
  assert.doesNotMatch(entryText, /<!-- Generated by cherry-works\./);
  assert.match(await held.read(inRepo(".cw/out/guide/team/general/index.md")), /<!-- Generated by cherry-works\./);
  const context = await charterAuthoringApp.predictMainContext({ exact: false });
  assert.equal(context.type, "MainContexts");
  if (context.type === "MainContexts") {
    const codexContext = context.data.contexts[0]!.data;
    const entryLoad = codexContext.sessionLoads.find((load) => load.data.id === "AGENTS.md")!;
    assert.equal(entryLoad.data.tokens, new InMemoryTokenCounter().countTokens(entryText));
    assert.equal(codexContext.sessionLoads.some((load) => load.data.id === "team/general"), false);
    assert.equal(codexContext.fileLoads.some((load) => load.data.id === "src/AGENTS.md"), true);
  }
  held.remove(guideFile);
  held.remove(inRepo(".cw/charter/guide/team/general/notes.md"));
  assert.equal((await charterAuthoringApp.build()).type, "PlanSummary");
  assert.doesNotMatch(await held.read(inRepo("AGENTS.md")), /Follow team\/general\./);
});

